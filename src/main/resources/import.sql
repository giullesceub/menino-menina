-- Carga automática do H2 para testes e desenvolvimento local.

CREATE TABLE IF NOT EXISTS funcionario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(120) NOT NULL,
 cpf VARCHAR(14) UNIQUE, telefone VARCHAR(20), login VARCHAR(50) NOT NULL UNIQUE,
 senha_hash VARCHAR(255) NOT NULL, perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('PROPRIETARIA','VENDEDOR')),
 ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS categoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS cliente (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(120) NOT NULL,
 cpf VARCHAR(14) UNIQUE, telefone VARCHAR(20), ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS fornecedor (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, razao_social VARCHAR(150) NOT NULL,
 nome_fantasia VARCHAR(150), cnpj VARCHAR(18) UNIQUE, telefone VARCHAR(20), email VARCHAR(120),
 ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS produto (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(150) NOT NULL,
 categoria_id BIGINT NOT NULL REFERENCES categoria(id), tamanho VARCHAR(20), cor VARCHAR(30),
 codigo_barras VARCHAR(50) UNIQUE,
 preco_venda NUMERIC(10,2) NOT NULL CHECK (preco_venda >= 0), estoque_atual INTEGER NOT NULL DEFAULT 0 CHECK (estoque_atual >= 0),
 fornecedor_id BIGINT REFERENCES fornecedor(id), ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS caixa (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, funcionario_abertura_id BIGINT NOT NULL REFERENCES funcionario(id),
 funcionario_fechamento_id BIGINT REFERENCES funcionario(id), data_abertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 data_fechamento TIMESTAMP, valor_abertura NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (valor_abertura >= 0),
 valor_fechamento_esperado NUMERIC(10,2) CHECK (valor_fechamento_esperado >= 0),
 valor_fechamento_informado NUMERIC(10,2) CHECK (valor_fechamento_informado >= 0),
 status VARCHAR(15) NOT NULL DEFAULT 'ABERTO' CHECK (status IN ('ABERTO','FECHADO'))
);
CREATE TABLE IF NOT EXISTS compra (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, fornecedor_id BIGINT NOT NULL REFERENCES fornecedor(id),
 data_compra TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, valor_total NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (valor_total >= 0)
);
CREATE TABLE IF NOT EXISTS item_compra (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, compra_id BIGINT NOT NULL REFERENCES compra(id) ON DELETE CASCADE,
 produto_id BIGINT NOT NULL REFERENCES produto(id), quantidade INTEGER NOT NULL CHECK (quantidade > 0),
 custo_unitario NUMERIC(10,2) NOT NULL CHECK (custo_unitario >= 0), subtotal NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0)
);
CREATE TABLE IF NOT EXISTS venda (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, funcionario_id BIGINT NOT NULL REFERENCES funcionario(id),
 cliente_id BIGINT REFERENCES cliente(id), data_venda TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 valor_total NUMERIC(10,2) NOT NULL CHECK (valor_total >= 0)
);
CREATE TABLE IF NOT EXISTS item_venda (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, venda_id BIGINT NOT NULL REFERENCES venda(id) ON DELETE CASCADE,
 produto_id BIGINT NOT NULL REFERENCES produto(id), quantidade INTEGER NOT NULL CHECK (quantidade > 0),
 preco_unitario NUMERIC(10,2) NOT NULL CHECK (preco_unitario >= 0), subtotal NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0)
);
CREATE TABLE IF NOT EXISTS pagamento_venda (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, venda_id BIGINT NOT NULL REFERENCES venda(id) ON DELETE CASCADE,
 forma_pagamento VARCHAR(25) NOT NULL CHECK (forma_pagamento IN ('DINHEIRO','PIX','CARTAO_DEBITO','CARTAO_CREDITO')),
 valor NUMERIC(10,2) NOT NULL CHECK (valor > 0)
);
CREATE TABLE IF NOT EXISTS movimentacao_caixa (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, caixa_id BIGINT NOT NULL REFERENCES caixa(id),
 funcionario_id BIGINT NOT NULL REFERENCES funcionario(id), venda_id BIGINT REFERENCES venda(id),
 tipo VARCHAR(15) NOT NULL CHECK (tipo IN ('ENTRADA','SAIDA')),
 categoria VARCHAR(25) NOT NULL CHECK (categoria IN ('VENDA','RETIRADA','ENTRADA_MANUAL')),
 valor NUMERIC(10,2) NOT NULL CHECK (valor > 0), descricao VARCHAR(255) NOT NULL,
 data_movimentacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS historico_funcionario (
 funcionario_id BIGINT NOT NULL, nome VARCHAR(120) NOT NULL, cpf VARCHAR(14), telefone VARCHAR(20),
 login VARCHAR(50) NOT NULL, perfil VARCHAR(20) NOT NULL, ativo BOOLEAN NOT NULL,
 timestamp_alteracao TIMESTAMP NOT NULL, tipo_atualizacao VARCHAR(1) NOT NULL CHECK (tipo_atualizacao IN ('I','A')), usuario_id BIGINT NOT NULL,
 PRIMARY KEY (funcionario_id, timestamp_alteracao)
);
CREATE TABLE IF NOT EXISTS historico_cliente (
 cliente_id BIGINT NOT NULL, nome VARCHAR(120) NOT NULL, cpf VARCHAR(14), telefone VARCHAR(20),
 ativo BOOLEAN NOT NULL, timestamp_alteracao TIMESTAMP NOT NULL, tipo_atualizacao VARCHAR(1) NOT NULL CHECK (tipo_atualizacao IN ('I','A')),
 usuario_id BIGINT NOT NULL, PRIMARY KEY (cliente_id, timestamp_alteracao)
);
CREATE TABLE IF NOT EXISTS historico_fornecedor (
 fornecedor_id BIGINT NOT NULL, razao_social VARCHAR(150) NOT NULL, nome_fantasia VARCHAR(150),
 cnpj VARCHAR(18), telefone VARCHAR(20), email VARCHAR(120), ativo BOOLEAN NOT NULL,
 timestamp_alteracao TIMESTAMP NOT NULL, tipo_atualizacao VARCHAR(1) NOT NULL CHECK (tipo_atualizacao IN ('I','A')), usuario_id BIGINT NOT NULL,
 PRIMARY KEY (fornecedor_id, timestamp_alteracao)
);
CREATE TABLE IF NOT EXISTS historico_produto (
 produto_id BIGINT NOT NULL, nome VARCHAR(150) NOT NULL, categoria_id BIGINT NOT NULL,
 tamanho VARCHAR(20), cor VARCHAR(30),  codigo_barras VARCHAR(50), preco_venda NUMERIC(10,2) NOT NULL, estoque_atual INTEGER NOT NULL,
 fornecedor_id BIGINT, ativo BOOLEAN NOT NULL,
 timestamp_alteracao TIMESTAMP NOT NULL, tipo_atualizacao VARCHAR(1) NOT NULL CHECK (tipo_atualizacao IN ('I','A')), usuario_id BIGINT NOT NULL,
 PRIMARY KEY (produto_id, timestamp_alteracao)
);

